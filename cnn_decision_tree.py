def secure_predict(input_data):
    """
    A secure validation loop to guarantee that inputs are formatted correctly
    before performing inference, preventing runtime crashes and security bugs.
    """
    try:
        # Ensure input is castable to float and has exactly the required number of features
        validated_features = [float(val) for val in input_data]
        if len(validated_features) != 4:
            raise ValueError("Input must contain exactly 4 numeric values (sepal length, sepal width, petal length, petal width).")

        # Reshape for prediction
        prediction_input = np.array(validated_features).reshape(1, -1)
        prediction_idx = best_model.predict(prediction_input)[0]
        prediction_name = data.target_names[prediction_idx]

        return {
            "status": "Success",
            "prediction": prediction_name,
            "class_id": int(prediction_idx)
        }
    except Exception as e:
        return {
            "status": "Error",
            "message": str(e)
        }

